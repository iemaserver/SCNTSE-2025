def main():
    print(f"Loading Round 1 DB from {ADMIT_DB_PATH}...")
    with open(ADMIT_DB_PATH, "r", encoding="utf-8") as f:
        r1_db = json.load(f)

    # Build reverse map: hall_ticket (str) → first matching entry (has sha256 key + aadhar)
    ht_to_entry: dict[str, dict] = {}
    ht_to_key: dict[str, str] = {}
    for sha_key, entry in r1_db.items():
        ht = str(entry.get("ht", "")).strip()
        if ht and ht not in ht_to_entry:
            ht_to_entry[ht] = entry
            ht_to_key[ht] = sha_key

    os.makedirs(UNMATCHED_DIR, exist_ok=True)

    r2_db: dict[str, dict] = {}
    matched, unmatched = [], []

    for ht_int, name in QUALIFIED.items():
        ht_str = str(ht_int)
        pdf_filename = f"{ht_int}_r2.pdf"
        pdf_src = os.path.join(R2_PDF_DIR, pdf_filename)

        if ht_str in ht_to_entry:
            entry = ht_to_entry[ht_str]
            sha_key = ht_to_key[ht_str]
            aadhar = entry.get("aadhar", "")

            # Write to r2_db using the SAME sha256 key (same email+aadhar)
            r2_db[sha_key] = {
                "name": entry.get("name", name),
                "ht":   ht_str,
                "aadhar": aadhar,
                "pdf":  f"/admit_round2/{pdf_filename}",
            }
            matched.append(ht_int)

            # Ensure the PDF stays in admit_round2/ (it's already there)
            if not os.path.exists(pdf_src):
                print(f"  ⚠  PDF missing for matched HT {ht_int}: {pdf_src}")
        else:
            unmatched.append(ht_int)
            # Move PDF to unmatched dir
            if os.path.exists(pdf_src):
                dst = os.path.join(UNMATCHED_DIR, pdf_filename)
                shutil.copy2(pdf_src, dst)
                print(f"  → Copied unmatched HT {ht_int} PDF to admit_round2_unmatched/")
            else:
                print(f"  ⚠  PDF missing for unmatched HT {ht_int}: {pdf_src}")

    # Write the Round 2 DB
    with open(R2_DB_OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(r2_db, f, ensure_ascii=False, indent=2)

    print(f"\n✓ admit_round2_db.json written → {R2_DB_OUT_PATH}")
    print(f"  Matched   (downloadable via website): {len(matched)}")
    print(f"  Unmatched (moved to unmatched dir):   {len(unmatched)}")

    if unmatched:
        print("\nUnmatched hall tickets (not in admit-db.json):")
        for ht in unmatched:
            print(f"  {ht}  {QUALIFIED[ht]}")


if __name__ == "__main__":
    main()
